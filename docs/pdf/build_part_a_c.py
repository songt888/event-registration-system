"""Assemble PDF Parts A to C (Issue #42) from the docs, so the PDF text stays identical to the repo.

Run from the repository root: python3 docs/pdf/build_part_a_c.py > docs/pdf/part-a-c.md
Links between docs become references to the PDF Part that holds the target (the PDF must not send the TA to repo files).
"""
import re
import subprocess
import sys

PARTS = [
    ("Part A. SRS and product scope", ["docs/srs.md", "docs/decisions.md"]),
    ("Part B. Feature inventory and traceability", ["docs/features.md", "docs/traceability.md"]),
    ("Part C. System-Level SDS", ["docs/system-sds.md"]),
]

# Where each linked doc appears in the PDF; docs not in the PDF are named in plain text.
WHERE = {
    "srs.md": "Part A", "decisions.md": "Part A", "features.md": "Part B", "traceability.md": "Part B",
    "system-sds.md": "Part C", "sprints/plan.md": "Part D", "plan.md": "Part D",
}


def where(target):
    path = target.split("#")[0].replace("../", "").removeprefix("docs/")
    if path in WHERE:
        return WHERE[path]
    if path.startswith("sprints/sprint-1/") and path != "sprints/sprint-1/issue-plan.md":
        return "Part E"
    if path.startswith("evidence/"):
        return "Part F"
    return None


def relink(match):
    text, target = match.group(1), match.group(2)
    if target.startswith(("http://", "https://", "#")):
        return match.group(0)
    part = where(target)
    return f"{text} ({part})" if part else f"{text} (team-internal file `{target.split('/')[-1]}`, repository)"


def main():
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    out = [f"<!-- Generated by docs/pdf/build_part_a_c.py from the docs at {commit}. Edit the docs, not this file. -->\n"]
    for title, files in PARTS:
        out.append(f"\n# {title}\n")
        for f in files:
            text = open(f, encoding="utf-8").read()
            text = re.sub(r"(?<!!)\[([^\]]+)\]\(([^)]+)\)", relink, text)
            # Each doc becomes a section of its Part: shift every heading down one level.
            text = re.sub(r"^(#{1,5}) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)
            out.append(f"\n<!-- source: {f} -->\n\n{text.strip()}\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
